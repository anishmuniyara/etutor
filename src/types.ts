/**
 * Content model. Field names follow context.md — the spec is the source of truth.
 *
 * A single permissive `Card` shape carries every field any category can use. Card
 * templates read only the fields they care about and each section self-suppresses
 * when its field is absent, so a partially-filled card still renders cleanly.
 */

export type TemplateId = 'explanation' | 'grammar' | 'comparison' | 'conversation'

export type Level = 'A1' | 'A2' | 'B1' | 'B2' | 'C1' | 'C2'

export interface Example {
  /** Where the sentence would naturally appear: Career, Travel, Email… (context.md §10) */
  context?: string
  sentence: string
}

export interface ComparisonItem {
  term: string
  meaning: string
}

export interface Alternative {
  term: string
  usage: string
}

export interface Turn {
  speaker: string
  text: string
}

export interface Card {
  /** Stable, URL-safe, never reused. All persistence keys off this. (context.md §8) */
  id: string
  term: string
  level: Level

  // Explanation / grammar
  meaning?: string
  /** Tenses use `definition` where other categories use `meaning` (context.md §6.1) */
  definition?: string
  usage?: string
  formula?: string
  partOfSpeech?: string
  businessCategory?: string
  /** Where an informal expression should NOT be used (context.md §6.10) */
  avoidIn?: string
  /** Why a conversation starter is used (context.md §6.8) */
  purpose?: string

  // Comparison
  items?: ComparisonItem[]
  difference?: string
  alternatives?: Alternative[]

  // Conversation
  /** situations.json uses `goal`; short_conversations.json uses `situation`. */
  goal?: string
  situation?: string
  conversation?: Turn[]
  keyExpressions?: string[]

  examples?: Example[]
  remember?: string[]
}

export interface CategoryMeta {
  /** Matches the JSON filename: `vocabulary` → public/content/vocabulary.json */
  slug: string
  name: string
  template: TemplateId
  /** SVG path data (24x24 viewBox), lifted from design v3. `icon2` may be empty. */
  icon: string
  icon2: string
  /** Regenerated by scripts/build-manifest.mjs so tiles never drift from the files. */
  count: number
}
